-- ---------- storage ----------
-- avatars/covers are intentionally public (they are shown on public profiles); everything else is private + signed URLs.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values
  ('avatars', 'avatars', true, 5242880, array['image/jpeg', 'image/png', 'image/webp']),
  ('covers', 'covers', true, 10485760, array['image/jpeg', 'image/png', 'image/webp']),
  ('post-media', 'post-media', false, 104857600, array['image/jpeg', 'image/png', 'image/webp', 'video/mp4', 'video/quicktime', 'video/webm']),
  ('message-media', 'message-media', false, 10485760, array['image/jpeg', 'image/png', 'image/webp']),
  ('journal-attachments', 'journal-attachments', false, 10485760, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

-- Convention: object path = '<auth uid>/<uuid>.<ext>' (generated by the client library, never user filenames)
create policy storage_own_write on storage.objects for insert to authenticated
  with check (bucket_id in ('avatars', 'covers', 'post-media', 'message-media', 'journal-attachments') and (storage.foldername(name))[1] = auth.uid()::text);
create policy storage_own_update on storage.objects for update to authenticated
  using ((storage.foldername(name))[1] = auth.uid()::text) with check ((storage.foldername(name))[1] = auth.uid()::text);
create policy storage_own_delete on storage.objects for delete to authenticated
  using ((storage.foldername(name))[1] = auth.uid()::text);
create policy storage_public_read on storage.objects for select to anon, authenticated using (bucket_id in ('avatars', 'covers'));
create policy storage_own_read on storage.objects for select to authenticated using ((storage.foldername(name))[1] = auth.uid()::text);
create policy storage_post_media_read on storage.objects for select to authenticated, anon using (
  bucket_id = 'post-media' and exists (select 1 from public.post_media pm where pm.storage_path = name and public.can_view_post(pm.post_id))
);
create policy storage_message_media_read on storage.objects for select to authenticated using (
  bucket_id = 'message-media' and exists (
    select 1 from public.message_media mm join public.messages m on m.id = mm.message_id
    where mm.storage_path = name and public.is_conversation_member(m.conversation_id))
);

-- ---------- places (Google Place IDs are storable; other cached fields expire after 30 days) ----------
create or replace function public.ensure_destination(
  p_place_id text, p_name text, p_lat double precision, p_lng double precision,
  p_country text default null, p_region text default null, p_category text default null
) returns uuid
language plpgsql security definer set search_path = public as $$
declare did uuid;
begin
  if auth.uid() is null then raise exception 'Not authenticated' using errcode = '42501'; end if;
  if p_place_id is null or char_length(p_place_id) not between 5 and 300 then raise exception 'Invalid place id' using errcode = '22023'; end if;
  if p_lat not between -90 and 90 or p_lng not between -180 and 180 then raise exception 'Invalid coordinates' using errcode = '22023'; end if;
  perform public.enforce_rate_limit(auth.uid(), 'ensure_destination', 300, interval '1 hour');
  insert into public.destinations (source, google_place_id, name, latitude, longitude, country, region, category, cached_at, cache_expires_at, created_by)
  values ('google_place', p_place_id, left(p_name, 200), p_lat, p_lng, left(p_country, 80), left(p_region, 120),
          case when exists (select 1 from public.destination_categories where slug = p_category) then p_category end, now(), now() + interval '30 days', auth.uid())
  on conflict (google_place_id) where google_place_id is not null do update
    set name = excluded.name, latitude = excluded.latitude, longitude = excluded.longitude, country = excluded.country,
        region = excluded.region, cached_at = now(), cache_expires_at = now() + interval '30 days'
  returning id into did;
  return did;
end $$;

create or replace function public.expire_google_place_cache() returns int
language plpgsql security definer set search_path = public as $$
declare c int;
begin
  if not public.is_privileged_context() then raise exception 'Not allowed' using errcode = '42501'; end if;
  update public.destinations set name = null, normalized_name = '', latitude = null, longitude = null, country = null, region = null, cache_expires_at = null
  where source = 'google_place' and cache_expires_at < now();
  get diagnostics c = row_count;
  return c;
end $$;
revoke all on function public.expire_google_place_cache() from public, anon, authenticated;

-- ---------- feed (keyset pagination; RLS enforces visibility, blocks and private accounts) ----------
create or replace function public.get_home_feed(
  p_scope text default 'following', p_limit int default 20, p_before timestamptz default null, p_before_id uuid default null
) returns table (
  post_id uuid, author_id uuid, username text, display_name text, avatar_url text, post_type public.post_type, caption text,
  destination_id uuid, trip_id uuid, created_at timestamptz, like_count bigint, comment_count bigint, liked_by_me boolean, saved_by_me boolean
) language sql stable security invoker as $$
  select p.id, p.author_id, pr.username, pr.display_name, pr.avatar_url, p.post_type, p.caption, p.destination_id, p.trip_id, p.created_at,
         (select count(*) from public.reactions r where r.post_id = p.id),
         (select count(*) from public.comments c where c.post_id = p.id and c.status = 'visible'),
         exists (select 1 from public.reactions r where r.post_id = p.id and r.user_id = auth.uid()),
         exists (select 1 from public.saved_items s where s.item_type = 'post' and s.item_id = p.id and s.user_id = auth.uid())
  from public.posts p
  join public.profiles pr on pr.id = p.author_id
  where p.publication_status = 'published'
    and (p_before is null or (p.created_at, p.id) < (p_before, coalesce(p_before_id, 'ffffffff-ffff-ffff-ffff-ffffffffffff'::uuid)))
    and (
      (p_scope = 'following' and (p.author_id = auth.uid() or exists (select 1 from public.follows f where f.follower_id = auth.uid() and f.following_id = p.author_id and f.status = 'accepted')))
      or (p_scope = 'discover' and p.visibility = 'public')
    )
  order by p.created_at desc, p.id desc
  limit least(greatest(p_limit, 1), 50);
$$;

-- ---------- search (relevance = trigram similarity + small recency boost; visibility via RLS) ----------
create or replace function public.search_all(p_query text, p_kind text default 'all', p_limit int default 10, p_offset int default 0)
returns table (kind text, id uuid, title text, subtitle text, handle text, score real)
language plpgsql stable security invoker as $$
declare q text := lower(trim(coalesce(p_query, '')));
begin
  if char_length(q) < 2 then return; end if;
  return query
  select * from (
    select 'profile'::text as kind, p.id, p.display_name as title, '@' || p.username as subtitle, p.username as handle,
           (extensions.similarity(lower(p.username), q) + extensions.similarity(lower(p.display_name), q))::real as score
    from public.profiles p where p_kind in ('all', 'profile') and p.account_visibility = 'public'
      and (p.username ilike '%' || q || '%' or p.display_name ilike '%' || q || '%')
    union all
    select 'destination', d.id, d.name, concat_ws(', ', d.region, d.country), d.slug,
           (extensions.similarity(d.normalized_name, q) + case when d.is_featured then 0.1 else 0 end)::real
    from public.destinations d where p_kind in ('all', 'destination') and d.is_published and d.name is not null and d.normalized_name ilike '%' || q || '%'
    union all
    select 'trip', t.id, t.title, null, t.slug,
           (extensions.similarity(lower(t.title), q) + 0.05)::real
    from public.trips t where p_kind in ('all', 'trip') and t.visibility = 'public' and t.status in ('planned', 'active', 'completed') and t.title ilike '%' || q || '%'
    union all
    select 'post', po.id, left(po.caption, 80), null, null,
           (extensions.similarity(lower(po.caption), q) * 0.5 + greatest(0, 0.2 - extract(epoch from now() - po.created_at) / 86400 / 365))::real
    from public.posts po where p_kind in ('all', 'post') and po.publication_status = 'published' and po.visibility = 'public' and po.caption ilike '%' || q || '%'
    union all
    select 'hashtag', h.id, '#' || h.tag, (select count(*) from public.post_hashtags ph where ph.hashtag_id = h.id)::text || ' posts', h.tag,
           extensions.similarity(h.tag, ltrim(q, '#'))::real
    from public.hashtags h where p_kind in ('all', 'hashtag') and not h.is_blocked and h.tag like ltrim(q, '#') || '%'
  ) r order by r.score desc nulls last, r.title limit least(p_limit, 50) offset greatest(p_offset, 0);
end $$;

-- ---------- discovery ----------
create or replace function public.trending_public_trips(p_limit int default 10)
returns table (id uuid, slug text, title text, owner_username text, saves bigint, published_at timestamptz)
language sql stable security invoker as $$
  select t.id, t.slug, t.title, pr.username,
         (select count(*) from public.saved_items s where s.item_type = 'trip' and s.item_id = t.id), t.published_at
  from public.trips t join public.profiles pr on pr.id = t.owner_id
  where t.visibility = 'public' and t.status in ('planned', 'active', 'completed') and pr.account_visibility = 'public'
  order by 5 desc, t.published_at desc limit least(p_limit, 50);
$$;

create or replace function public.suggest_users(p_limit int default 10)
returns table (id uuid, username text, display_name text, avatar_url text, shared_interests int)
language sql stable security invoker as $$
  select p.id, p.username, p.display_name, p.avatar_url,
         coalesce(cardinality(array(select unnest(p.travel_interests) intersect select unnest(me.travel_interests))), 0)
  from public.profiles p
  left join public.profiles me on me.id = auth.uid()
  where p.account_visibility = 'public' and p.id is distinct from auth.uid()
    and not exists (select 1 from public.follows f where f.follower_id = auth.uid() and f.following_id = p.id)
  order by 5 desc, p.created_at desc limit least(p_limit, 50);
$$;

-- Everything the public trip page needs, in one RLS-filtered call. Never includes raw GPS.
create or replace function public.get_public_trip(p_slug text) returns jsonb
language plpgsql stable security invoker as $$
declare t public.trips; result jsonb;
begin
  select * into t from public.trips where slug = p_slug;
  if t.id is null then return null; end if;
  select jsonb_build_object(
    'trip', jsonb_build_object('id', t.id, 'slug', t.slug, 'title', t.title, 'description', t.description, 'cover_image_url', t.cover_image_url,
            'start_date', t.start_date, 'end_date', t.end_date, 'status', t.status, 'visibility', t.visibility, 'published_at', t.published_at),
    'owner', (select jsonb_build_object('username', p.username, 'display_name', p.display_name, 'avatar_url', p.avatar_url) from public.profiles p where p.id = t.owner_id),
    'stops', coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'order', s.stop_order, 'notes', s.notes, 'status', s.completion_status,
              'destination', case when d.id is null then jsonb_build_object('name', s.custom_name) else
                 jsonb_build_object('id', d.id, 'slug', d.slug, 'name', d.name, 'region', d.region, 'country', d.country, 'latitude', d.latitude, 'longitude', d.longitude) end)
              order by s.stop_order) from public.trip_stops s left join public.destinations d on d.id = s.destination_id where s.trip_id = t.id), '[]'),
    'route_preview', (select to_jsonb(r) - 'published_by' from public.trip_route_previews r where r.trip_id = t.id),
    'progress', (select to_jsonb(pg) from public.trip_progress(t.id) pg)
  ) into result;
  return result;
end $$;

-- Minimal public card for private accounts is exposed via get_profile_card (see RLS migration).
create or replace function public.mark_notifications_read(p_ids uuid[] default null) returns int
language plpgsql security invoker as $$
declare c int;
begin
  update public.notifications set read_at = now() where recipient_id = auth.uid() and read_at is null and (p_ids is null or id = any (p_ids));
  get diagnostics c = row_count;
  return c;
end $$;
